/**
 * Returns a random word that STRICTLY starts with the letters typed by the user.
 * Example: typed "aba" -> returns "abacada" or other word starting with "aba".
 */
export function getPrefixMatchAutocorrect(rawWord) {
  if (!rawWord || typeof rawWord !== 'string') return null;

  const clean = rawWord.toLowerCase().replace(/[^a-z0-9]/g, '');
  if (!clean || clean.length < 1) return null;

  // 1. Search our extensive dictionary for words starting with `clean`
  const matches = CURSED_PREFIX_WORDS.filter(
    (w) => w.toLowerCase().startsWith(clean) && w.toLowerCase() !== clean
  );

  let selectedWord = '';

  if (matches.length > 0) {
    // Pick a random matching word that starts with the same letters
    selectedWord = matches[Math.floor(Math.random() * matches.length)];
  } else {
    // Procedural generation: MUST strictly match the first letters typed by user!
    // Example: user typed "aba" -> "abacada"!
    const proceduralSuffixes = [
      'cada',
      'cadabra',
      'tion',
      'ology',
      'phobia',
      'mancer',
      '-unya-na',
      '-ugma-na',
      '-in-progress',
      '-delayed',
      '-postponed',
      '-deluxe',
      '-ish',
      '-esque',
    ];

    // If prefix ends with "aba", guarantee "abacada" as preferred candidate
    if (clean.endsWith('aba')) {
      selectedWord = clean + 'cada';
    } else {
      const chosenSuffix =
        proceduralSuffixes[Math.floor(Math.random() * proceduralSuffixes.length)];
      selectedWord = clean + chosenSuffix;
    }
  }

  // Preserve casing from original typed word
  const isAllUpper = rawWord.length > 1 && rawWord === rawWord.toUpperCase();
  const isCapitalized = /^[A-Z]/.test(rawWord);

  let formattedWord = selectedWord;
  if (isAllUpper) {
    formattedWord = selectedWord.toUpperCase();
  } else if (isCapitalized) {
    formattedWord = selectedWord.charAt(0).toUpperCase() + selectedWord.slice(1);
  } else {
    formattedWord = selectedWord.toLowerCase();
  }

  return {
    original: rawWord,
    transformed: formattedWord,
    details: `Autocorrected "${rawWord}" → "${formattedWord}"`,
  };
}

/**
 * Actively enforces lowercase after periods (e.g. ". " or ".\n")
 * Even if user holds Shift or Caps Lock, first character after a period is forced lowercase.
 */
export function shouldEnforceLowercaseAfterPeriod(textBeforeCursor) {
  if (!textBeforeCursor || typeof textBeforeCursor !== 'string') return false;
  return /\.\s+$/.test(textBeforeCursor);
}
